"""Build the standalone tester web app from the prototype source.

Usage:  python3 tester-web/build.py
Reads   prototype-source/project/Main.dc.html and Pack.dc.html
Writes  tester-web/app.js (current design), app-hearth.js (Hearth design,
        made with prototype-source/tools/make_hearth.py) and pack.js
"""
import html, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'prototype-source', 'project')
sys.path.insert(0, os.path.join(HERE, '..', 'prototype-source', 'tools'))
from make_hearth import hearth  # noqa: E402
VOID = {'input', 'br', 'img', 'meta', 'link', 'hr', 'area', 'base', 'col', 'source', 'wbr'}
TOKEN = re.compile(r'<!--.*?-->|<(/?)([a-zA-Z][\w-]*)((?:\s+[^\s=>/]+(?:="[^"]*")?)*)\s*(/?)>', re.S)
ATTR = re.compile(r'([^\s=>/]+)(?:="([^"]*)")?')


def parse(markup):
    """Tiny parser for our own well-formed markup. Keeps attribute case (onClick)."""
    root = ['#root', {}, []]
    stack = [root]
    pos = 0
    for m in TOKEN.finditer(markup):
        if m.start() > pos:
            stack[-1][2].append(html.unescape(markup[pos:m.start()]))
        pos = m.end()
        if m.group(0).startswith('<!--'):
            continue
        closing, tag, attrs, selfclose = m.group(1), m.group(2), m.group(3), m.group(4)
        if closing:
            while len(stack) > 1:
                node = stack.pop()
                if node[0] == tag:
                    break
            continue
        a = {}
        for am in ATTR.finditer(attrs or ''):
            name, val = am.group(1), am.group(2)
            if name.startswith('hint-'):
                continue
            a[name] = html.unescape(val) if val is not None else True
        node = [tag, a, []]
        stack[-1][2].append(node)
        if not selfclose and tag.lower() not in VOID:
            stack.append(node)
    if pos < len(markup):
        stack[-1][2].append(html.unescape(markup[pos:]))
    return root


def squeeze(node):
    """Drop whitespace-only text between elements."""
    if isinstance(node, str):
        return node
    kids = []
    for k in node[2]:
        if isinstance(k, str) and not k.strip():
            continue
        kids.append(squeeze(k))
    return [node[0], node[1], kids]


def build(name, out, links, design=None, transform=None):
    src = open(os.path.join(SRC, name), encoding='utf-8').read()
    if transform:
        src = transform(src)
    body = src.split('<x-dc>')[1].split('</x-dc>')[0]
    helmet = re.search(r'<helmet>(.*?)</helmet>', body, re.S)
    head = helmet.group(1) if helmet else ''
    markup = re.sub(r'<helmet>.*?</helmet>', '', body, flags=re.S)
    for a, b in links.items():
        markup = markup.replace('href="%s"' % a, 'href="%s"' % b)
    script = re.search(r'<script type="text/x-dc"[^>]*>(.*?)</script>', src, re.S).group(1)
    tree = squeeze(parse(markup))
    js = '/* Generated by build.py from %s. Do not edit by hand. */\n' % name
    if design:
        # each design lives in its own scope so two can be loaded side by side
        js += 'window.DC_APPS = window.DC_APPS || {};\n(function () {\n'
        js += script + '\nwindow.DC_APPS[%s] = { head: %s, tree: %s, Component };\n})();\n' % (
            json.dumps(design), json.dumps(head), json.dumps(tree, ensure_ascii=False))
    else:
        js += 'window.DC_HEAD = %s;\n' % json.dumps(head)
        js += 'window.DC_TREE = %s;\n' % json.dumps(tree, ensure_ascii=False)
        js += script + '\nwindow.DC_COMPONENT = Component;\n'
    open(os.path.join(HERE, out), 'w', encoding='utf-8').write(js)
    print('wrote', out, len(js) // 1024, 'KB')


build('Main.dc.html', 'app.js', {'Pack.dc.html': 'pack.html'}, design='current')
build('Main.dc.html', 'app-hearth.js', {'PackHearth.dc.html': 'pack.html?design=hearth'}, design='hearth', transform=hearth)
build('Pack.dc.html', 'pack.js', {})
build('Pack.dc.html', 'pack-hearth.js', {}, transform=hearth)


def stamp(page, files):
    """Add ?v=<content hash> to each script/stylesheet so browsers fetch changed files at once
    (GitHub Pages lets browsers keep files for 10 minutes)."""
    import hashlib
    path = os.path.join(HERE, page)
    s = open(path, encoding='utf-8').read()
    for f in files:
        v = hashlib.sha1(open(os.path.join(HERE, f), 'rb').read()).hexdigest()[:8]
        # matches "file" in attributes and 'file' inside the pack page's loader script
        s = re.sub(r'(["\'])%s(?:\?v=[0-9a-f]+)?(["\'])' % re.escape(f), r'\g<1>%s?v=%s\g<2>' % (f, v), s)
    open(path, 'w', encoding='utf-8').write(s)
    print('stamped', page)


stamp('index.html', ['tester.css', 'config.js', 'runtime.js', 'app.js', 'app-hearth.js', 'tester.js'])
stamp('pack.html', ['runtime.js', 'pack.js', 'pack-hearth.js'])
